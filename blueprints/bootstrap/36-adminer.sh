# Adminer: a database browser in a single PHP file.
#
# Deliberately not the Docker image. It is served by PHP's own built-in web
# server behind a systemd unit, which means no nginx, no php-fpm socket path that
# differs per distro, and no dependency on Docker being up before the GUI works.
# That server is single threaded and not meant for production traffic, which is
# the right trade for a single-user database GUI on a dev VM.
#
#   VM_ADMINER_INSTALL          whether to do any of this
#   VM_ADMINER_PORT             the port to serve on
#   VM_ADMINER_VERSION          the Adminer release to fetch
#   VM_ADMINER_PHP_DRIVER_APT   the PHP extension for this engine, on apt
#   VM_ADMINER_PHP_DRIVER_DNF   the same, on dnf
if ! is_true "${VM_ADMINER_INSTALL:-false}"; then
    log "adminer not requested"
    return 0 2>/dev/null || exit 0
fi

PORT="${VM_ADMINER_PORT:-3800}"
VERSION="${VM_ADMINER_VERSION:-4.8.1}"
ROOT=/usr/share/adminer
STATE=/var/lib/vm-bootstrap/adminer
install -d /var/lib/vm-bootstrap

write_state() {
    printf '%s\t%s\t%s\t%s\n' "${1:-unknown}" "${2:-}" "$VERSION" "$PORT" > "$STATE"
}

# ------------------------------------------------------------------------- php
if [[ "$PKG_MANAGER" == "apt" ]]; then
    driver="${VM_ADMINER_PHP_DRIVER_APT:-}"
else
    driver="${VM_ADMINER_PHP_DRIVER_DNF:-}"
fi

pkgs=(php-cli)
[[ -n "$driver" ]] && pkgs+=("$driver")
pkg_install "${pkgs[@]}"

if ! have_cmd php; then
    warn "php is not on the path after installing ${pkgs[*]}"
    write_state failed "php missing"
    return 1 2>/dev/null || exit 1
fi
log "$(php --version | head -1)"

# ---------------------------------------------------------------- adminer itself
install -d -m 0755 "$ROOT"
TARGET="$ROOT/index.php"

if [[ -s "$TARGET" ]]; then
    log "adminer already present at $TARGET"
else
    url="https://github.com/vrana/adminer/releases/download/v${VERSION}/adminer-${VERSION}.php"
    log "downloading adminer ${VERSION}"
    if ! curl -fsSL "$url" -o "$TARGET"; then
        warn "could not download adminer from $url"
        warn "  check the version exists, or set Database.Adminer.Version to one that does"
        rm -f "$TARGET"
        write_state failed "download failed"
        return 1 2>/dev/null || exit 1
    fi
    chmod 0644 "$TARGET"
fi

# A PHP file that does not parse would fail as a blank page in the browser, which
# is a poor way to find out. Check now.
if ! php -l "$TARGET" >/dev/null 2>&1; then
    warn "$TARGET is not valid PHP; the download was probably truncated or an error page"
    rm -f "$TARGET"
    write_state failed "invalid php"
    return 1 2>/dev/null || exit 1
fi

selinux_restore "$ROOT"

# ------------------------------------------------------------------- the service
UNIT=/etc/systemd/system/adminer.service
log "writing $UNIT"
cat > "$UNIT" <<UNITFILE
[Unit]
# GENERATED by vm-bootstrap. Edit Database.Adminer in vm.config.yaml.
Description=Adminer database browser (php built-in server)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
# Binds all addresses so the route works from the Windows host and from the other
# VMs on this switch, not just from inside the guest.
ExecStart=/usr/bin/php -S 0.0.0.0:${PORT} -t ${ROOT}
Restart=on-failure
RestartSec=5
# Adminer only ever reads its own file and talks to the database over the network.
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full

[Install]
WantedBy=multi-user.target
UNITFILE
chmod 0644 "$UNIT"

firewall_allow_port "$PORT"

systemctl daemon-reload
systemctl enable --now adminer.service

# ---------------------------------------------------------------- verification
HOSTNAME_STATIC="$(hostnamectl --static 2>/dev/null || hostname)"

# Wire the link to the database this machine actually installed, so the login
# form arrives with everything filled in except the password.
#
# Adminer picks its driver from the NAME of the first query parameter, which is
# not obvious and is why this is built here rather than left to a person to
# remember: PostgreSQL is ?pgsql=<host>, MySQL is ?server=<host>. The value is
# the server, and &username= fills the account.
#
# Checked against the running instance: the returned form comes back with
# value="pgsql" selected, auth[server] value="localhost" and auth[username]
# value="postgres". The password is the only field left, and deliberately so -
# see the note about auto login in vm.config.yaml.
ROUTE="http://${HOSTNAME_STATIC}.local:${PORT}/"
case "${VM_DB_ENGINE:-}" in
    postgres) ROUTE="${ROUTE}?pgsql=localhost&username=postgres" ;;
    mysql)    ROUTE="${ROUTE}?server=localhost&username=root" ;;
    *)        : ;;   # no engine: leave the plain URL, there is nothing to wire to
esac

ok=false
for _ in $(seq 1 10); do
    # A 200 proves php started, parsed adminer, and is answering on the port.
    code="$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:${PORT}/" 2>/dev/null || true)"
    if [[ "$code" == "200" ]]; then ok=true; break; fi
    sleep 2
done

if $ok; then
    log "adminer ${VERSION} is serving on port ${PORT}"
    log "  open  ${ROUTE}"
    if [[ -n "${VM_DB_ENGINE:-}" ]]; then
        log "  that link arrives pre-filled for ${VM_DB_ENGINE}; type the password and go"
    else
        log "  no database on this machine, so the form starts empty"
    fi
    write_state running "$ROUTE"
else
    warn "adminer is installed but not answering on port ${PORT}"
    warn "  check: systemctl status adminer.service"
    write_state failed "not answering on port ${PORT}"
    return 1 2>/dev/null || exit 1
fi
