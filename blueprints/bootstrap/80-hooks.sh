# Run the post-start hooks from config.
#
# The script itself was rendered on the host from Hooks.PostStart and
# Hooks.PostStartFile, so there is nothing to assemble here: this step decides who
# runs it, from where, and whether it also runs on every subsequent boot.
#
#   VM_HOOKS_SCRIPT        the rendered script, or blank if there are no hooks
#   VM_HOOKS_RUN_AS        'user' or 'root'
#   VM_HOOKS_WORKING_DIR   absolute, '~' relative, or blank for that user's home
#   VM_HOOKS_EVERY_BOOT    also install a systemd unit
SCRIPT="${VM_HOOKS_SCRIPT:-}"

if [[ -z "$SCRIPT" ]]; then
    log "no post-start hooks configured"
    return 0 2>/dev/null || exit 0
fi

if [[ ! -f "$SCRIPT" ]]; then
    warn "Hooks are configured but $SCRIPT is missing from the seed"
    return 1 2>/dev/null || exit 1
fi

RUN_AS="${VM_HOOKS_RUN_AS:-user}"
RUN_USER="$VM_PRIMARY_USER"
[[ "$RUN_AS" == "root" ]] && RUN_USER=root

HOME_DIR="$(getent passwd "$RUN_USER" | cut -d: -f6)"
[[ -n "$HOME_DIR" ]] || HOME_DIR=/root

WORKDIR="${VM_HOOKS_WORKING_DIR:-}"
if [[ -z "$WORKDIR" || "$WORKDIR" == "~" ]]; then
    WORKDIR="$HOME_DIR"
elif [[ "$WORKDIR" == "~/"* ]]; then
    WORKDIR="$HOME_DIR/${WORKDIR#~/}"
fi

if [[ ! -d "$WORKDIR" ]]; then
    warn "Hooks.WorkingDirectory '$WORKDIR' does not exist; creating it"
    install -d -o "$RUN_USER" "$WORKDIR" || {
        warn "could not create $WORKDIR"
        return 1 2>/dev/null || exit 1
    }
fi

chmod 0755 "$SCRIPT"

LOG_FILE=/var/log/vm-post-start.log

# ------------------------------------------------------------------ every boot
# A unit, so the same script also runs on every subsequent start. Installed
# before the first run so that run happens through the unit rather than twice.
if is_true "${VM_HOOKS_EVERY_BOOT:-false}"; then
    UNIT=/etc/systemd/system/vm-post-start.service
    log "installing $UNIT so the hooks run on every boot"
    cat > "$UNIT" <<UNITFILE
[Unit]
# GENERATED by vm-bootstrap. Edit Hooks in vm.config.yaml.
Description=vm-bootstrap post-start hooks
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
User=${RUN_USER}
WorkingDirectory=${WORKDIR}
ExecStart=${SCRIPT}
StandardOutput=append:${LOG_FILE}
StandardError=append:${LOG_FILE}

[Install]
WantedBy=multi-user.target
UNITFILE
    chmod 0644 "$UNIT"
    touch "$LOG_FILE"
    chmod 0644 "$LOG_FILE"

    systemctl daemon-reload
    # --now runs it here as well, which is the first-boot run.
    if systemctl enable --now vm-post-start.service; then
        log "post-start hooks ran, and will run again on every boot"
        log "  output: $LOG_FILE   and  journalctl -u vm-post-start.service"
        return 0 2>/dev/null || exit 0
    fi
    warn "the post-start hooks failed; see $LOG_FILE"
    warn "  the unit stays enabled, so they will run again on the next boot"
    tail -20 "$LOG_FILE" 2>/dev/null | sed 's/^/    /' || true
    return 1 2>/dev/null || exit 1
fi

# ------------------------------------------------------------------- run once
log "running post-start hooks as $RUN_USER in $WORKDIR"

# Output goes to its own file as well as this step's log, so a hook that prints a
# lot does not have to be dug out of the middle of the bootstrap log.
if [[ "$RUN_USER" == "root" ]]; then
    ( cd "$WORKDIR" && "$SCRIPT" ) 2>&1 | tee -a "$LOG_FILE"
    rc=${PIPESTATUS[0]}
else
    # A login shell, so nvm, ddev and anything else on the user's PATH is present
    # exactly as it would be if they had logged in and typed the command.
    sudo -iu "$RUN_USER" bash -lc "cd $(printf '%q' "$WORKDIR") && $(printf '%q' "$SCRIPT")" 2>&1 | tee -a "$LOG_FILE"
    rc=${PIPESTATUS[0]}
fi
chmod 0644 "$LOG_FILE" 2>/dev/null || true

if [[ $rc -eq 0 ]]; then
    log "post-start hooks finished, output in $LOG_FILE"
else
    warn "post-start hooks exited $rc; see $LOG_FILE"
    warn "  fix the commands in Hooks.PostStart, then: sudo vm-bootstrap --only 80-hooks --force"
    return 1 2>/dev/null || exit 1
fi
